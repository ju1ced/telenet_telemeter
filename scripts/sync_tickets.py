#!/usr/bin/env python3
"""Generate the ticket register and board from GitHub (requires authenticated gh)."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys


STATES = ("Backlog", "In uitvoering", "Review/validatie", "Klaar", "Geblokkeerd")
HEADER = """<!-- Generated by scripts/sync_tickets.py; edit the GitHub issues/milestones instead. -->

GitHub is de bron voor inhoud, status, prioriteit en sprintindeling. Bewerk de issues
en milestones; deze bestanden worden automatisch opnieuw opgebouwd.
Zie [synchronisatie-instructies](docs/ticket-sync.md) voor lokaal verversen.
"""


def fetch_all(repository, resource):
    """Fetch every API page, including closed issues and milestones."""
    result = subprocess.run(
        ["gh", "api", "--paginate",
         f"repos/{repository}/{resource}?state=all&per_page=100"],
        check=True, capture_output=True, text=True,
    )
    # Older gh versions emit consecutive JSON arrays and lack --slurp.
    decoder = json.JSONDecoder()
    remaining = result.stdout.lstrip()
    items = []
    while remaining:
        page, end = decoder.raw_decode(remaining)
        items.extend(page)
        remaining = remaining[end:].lstrip()
    return items


def status(issue):
    if issue["state"] == "closed":
        return "Klaar"
    labels = {label["name"] for label in issue["labels"]}
    for label, state in (("status:blocked", "Geblokkeerd"),
                         ("status:review", "Review/validatie"),
                         ("status:in-progress", "In uitvoering")):
        if label in labels:
            return state
    return "Backlog"


def cell(value):
    return str(value).replace("|", "&#124;").replace("\r", " ").replace("\n", " ")


def source_body(issue):
    """Remove import bookkeeping and metadata that is now derived from labels."""
    body = issue.get("body") or ""
    body = re.sub(r"<!-- imported-from:.*?-->", "", body)
    body = body.split("\n\n---\n\nGeïmporteerd uit `tickets.md` en `kanban.md`", 1)[0]
    body = re.sub(r"^- \*\*(?:Fase|Prioriteit):\*\*[^\n]*\n?", "", body, flags=re.M)
    return body.strip()


def render_documents(repository, issues, milestones):
    tickets = []
    for issue in issues:
        match = re.match(r"^(TM-\d+):?\s+(.+)", issue["title"])
        if match and "pull_request" not in issue:
            tickets.append((match[1], match[2], issue))
    tickets.sort(key=lambda t: (int(t[0][3:]), t[2]["number"]))
    ids = [ticket_id for ticket_id, _, _ in tickets]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate TM ticket IDs; reconcile the GitHub issues first")
    if not tickets:
        raise ValueError("No TM tickets found; refusing to overwrite the register")
    urls = {ticket_id: issue["html_url"] for ticket_id, _, issue in tickets}

    def link_ids(text):
        # Existing Markdown links already point to their GitHub issues.
        return re.sub(r"(?<!\[)\bTM-\d+\b", lambda m:
                      f"[{m[0]}]({urls[m[0]]})" if m[0] in urls else m[0], text)

    register = ["# Ticketregister – Telenet Telemeter\n", HEADER,
                f"[GitHub issues](https://github.com/{repository}/issues) · "
                f"[Sprints](https://github.com/{repository}/milestones) · [Kanban](kanban.md)\n",
                "Bestandsverwijzingen zijn relatief aan `custom_components/telenet_telemeter/`, tenzij anders vermeld.\n"]
    board = ["# Kanban – Telenet Telemeter\n", HEADER,
             f"[GitHub issues](https://github.com/{repository}/issues) · "
             f"[Sprints](https://github.com/{repository}/milestones) · [Ticketregister](tickets.md)\n",
             "P0 = blokkerende bug · P1 = belangrijk · P2 = nice to have.\n",
             "## Sprints\n",
             "| Sprint | Status | Gereed / totaal | Deadline |",
             "| --- | --- | --- | --- |"]
    for milestone in sorted(milestones, key=lambda m: m["number"]):
        members = [i for _, _, i in tickets
                   if i.get("milestone") and i["milestone"]["number"] == milestone["number"]]
        done = sum(i["state"] == "closed" for i in members)
        due = milestone["due_on"][:10] if milestone.get("due_on") else "Niet gepland"
        board.append(f"| [{cell(milestone['title'])}]({milestone['html_url']}) | "
                     f"{'Afgesloten' if milestone['state'] == 'closed' else 'Open'} | "
                     f"{done} / {len(members)} | {due} |")
    rows = {state: [] for state in STATES}
    for ticket_id, title, issue in tickets:
        labels = {label["name"] for label in issue["labels"]}
        priority = next((p for p in ("P0", "P1", "P2") if p in labels), "—")
        phase = next((label.split(":", 1)[1] for label in sorted(labels)
                      if label.startswith("phase:")), "—")
        milestone = issue.get("milestone")
        sprint = (f"[{cell(milestone['title'])}]({milestone['html_url']})"
                  if milestone else "Niet ingepland")
        state = status(issue)
        body = source_body(issue)
        register.extend([
            f'\n<a id="{ticket_id.lower()}"></a>\n',
            f"## {ticket_id} {title}\n",
            f"- **GitHub:** [#{issue['number']}]({issue['html_url']})",
            f"- **Status:** {state}", f"- **Prioriteit:** {priority}",
            f"- **Fase:** {phase}", f"- **Sprint:** {sprint}\n", link_ids(body) + "\n",
        ])
        dependency_line = re.search(r"^.*\*\*Afhankelijkheden:\*\*([^\n]*)", body, re.M)
        deps = list(dict.fromkeys(re.findall(r"TM-\d+", dependency_line[1]))) if dependency_line else []
        dependencies = ", ".join(link_ids(dep) for dep in deps) or "—"
        rows[state].append(f"| [{ticket_id}]({issue['html_url']}) | {cell(title)} | "
                           f"{priority} | {sprint} | {dependencies} |")
    for state in STATES:
        board.append(f"\n## {state}\n")
        if rows[state]:
            board.extend(["| Ticket | Onderwerp | Prioriteit | Sprint | Afhankelijkheid |",
                          "| --- | --- | --- | --- | --- |", *rows[state]])
        else:
            board.append("Geen tickets.")
    return {"tickets.md": "\n".join(register).rstrip() + "\n",
            "kanban.md": "\n".join(board).rstrip() + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default=os.environ.get(
        "GITHUB_REPOSITORY", "ju1ced/telenet_telemeter"))
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="Fail if the files differ from GitHub")
    args = parser.parse_args()
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", args.repository):
        parser.error("--repository must be owner/name")
    try:
        documents = render_documents(args.repository,
                                     fetch_all(args.repository, "issues"),
                                     fetch_all(args.repository, "milestones"))
    except subprocess.CalledProcessError as error:
        print(error.stderr.strip(), file=sys.stderr)
        return 1
    changed = []
    for name, content in documents.items():
        path = args.output_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            changed.append(name)
            if not args.check:
                path.write_text(content, encoding="utf-8")
    print(("Out of date: " if args.check else "Updated: ") + ", ".join(changed)
          if changed else "Ticket files are up to date.")
    return int(args.check and bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
